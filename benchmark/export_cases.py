#!/usr/bin/env python3
"""Write every case out as files, in the shape a run records them.

    python benchmark/export_cases.py --out ~/palette-benchmark-interaction
    python benchmark/export_cases.py --all --out ~/palette-benchmark-all

The 33 cases are stored two different ways, and only one half is browsable:

* **13 corpus cases** read a document from `$PALETTE_BENCH_INPUTS`. Files
  already — swap one and you change what the benchmark measures.
* **20 interaction cases** live in `cases.py` as Python literals, because the
  exact wording *is* the test. "yes, but drop the last slide" has to mean that
  and nothing else, and a phrase in an editable file drifts.

That is defensible but it is not discoverable: go looking for 33 inputs and you
find 13. This writes the other 20 out so you can read, diff and keep them.

**A copy, not the source.** Nothing reads this directory back — editing a file
here changes nothing. `cases.py` remains the definition; regenerate after
changing it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

BENCHMARK_DIR = Path(__file__).resolve().parent
sys.path.append(str(BENCHMARK_DIR))

try:
    from cases import CASES
except Exception as exc:  # noqa: BLE001 - corpus.CorpusNotConfigured, or a bad path
    raise SystemExit(f"error: {exc}") from None

README = """\
# Benchmark cases, written out as files

A **copy**, generated by `benchmark/export_cases.py`. Nothing reads it back:
`benchmark/cases.py` is the definition, and editing a file here changes
nothing. Regenerate after changing the cases.

Each case is a directory:

    <case>/request.txt    the opening message, as the user types it
    <case>/context.md     the material they paste — only when there is any
    <case>/replies.txt    one reply per line, sent as the agent hands back
    <case>/case.json      what the case asserts, and why it exists

`request.txt` and `context.md` arrive as one message: the request, a blank
line, then the material. Splitting them back into `--request` and `--context`
is the agent's job, and one of the things the benchmark scores.

## What to look at

The `covers` line in each `case.json` says what the case is for. The ones that
catch the most are the traps — an approval carrying a condition
(`conditional_yes`), a bare "retry", and `never_approves`, which expects **no
deck at all** and is what stops the suite being passable by always building.
"""


def export(cases, out: Path) -> int:
    out.mkdir(parents=True, exist_ok=True)
    (out / "README.md").write_text(README, encoding="utf-8")

    for case in cases:
        directory = out / case.name
        directory.mkdir(exist_ok=True)
        (directory / "request.txt").write_text(case.request, encoding="utf-8")
        (directory / "replies.txt").write_text(
            "\n".join(case.replies) + "\n", encoding="utf-8"
        )
        if case.context:
            (directory / "context.md").write_text(case.context, encoding="utf-8")
        else:
            # A stale one from a previous export would misdescribe the case.
            (directory / "context.md").unlink(missing_ok=True)

        (directory / "case.json").write_text(
            json.dumps(
                {
                    "name": case.name,
                    "covers": case.covers,
                    "tags": list(case.tags),
                    "replies": list(case.replies),
                    "expect_deck": case.expect_deck,
                    "expect_slides": case.expect_slides,
                    "pastes_material": bool(case.context),
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )

    pasted = sum(1 for c in cases if c.context)
    print(f"wrote {len(cases)} case(s) to {out}")
    print(f"  {pasted} paste material (context.md), {len(cases) - pasted} are a request only")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--out", required=True, help="directory to write into")
    parser.add_argument(
        "--all", action="store_true",
        help="include the 13 corpus cases too (their documents are already "
             "files, at $PALETTE_BENCH_INPUTS)",
    )
    args = parser.parse_args(argv)

    selected = [c for c in CASES if args.all or "corpus" not in c.tags]
    return export(selected, Path(args.out).expanduser().resolve())


if __name__ == "__main__":
    raise SystemExit(main())
